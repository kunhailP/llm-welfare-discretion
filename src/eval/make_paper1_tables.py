"""Paper 1 (NAACL preliminary) tables from the scored Design B runs. No model calls; reads
results/rules_pilot/score.json (first-token, 4 models) and results/rules_think/score_<model>.json (thinking, 3 models).
Writes docs/paper1/tables.md. Usage: python src/eval/make_paper1_tables.py
"""
import json, pathlib
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[2]
FT = json.load(open(ROOT / "results/rules_pilot/score.json"))
MODELS = ["qwen3-8b", "ministral3-8b", "qwen3-14b", "qwen3-32b-awq"]
THINK = {m: json.load(open(p)) for m in MODELS if (p := ROOT / f"results/rules_think/score_{m}.json").exists()}
THINK = {m: v[list(v)[0]] for m, v in THINK.items()}
TASKS = ["gross", "elig", "abawd"]
NAME = {"qwen3-8b": "Qwen3-8B", "ministral3-8b": "Ministral-3-8B", "qwen3-14b": "Qwen3-14B", "qwen3-32b-awq": "Qwen3-32B-AWQ"}


def ci(v):
    return f"{v[0]:+.3f} [{v[1]:+.3f}, {v[2]:+.3f}]"


def think_acc(m):
    acc = defaultdict(list)
    for k, v in THINK[m]["accuracy"].items():
        task, sub = k.split("|")[0], k.split("|")[-1]
        acc[(task, sub)].append(v)
    return {k: sum(x) / len(x) for k, x in acc.items()}


out = ["# Paper 1 tables (generated by src/eval/make_paper1_tables.py; do not edit by hand)", ""]
out += ["## T1. Competence: thinking off (balanced accuracy, first-token) vs thinking on (mean cell accuracy, generated verdict)",
        "", "| model | gross off | elig off | ABAWD off | gross on | elig on | ABAWD on | tokens (on) |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for m in MODELS:
    b = FT[m]["balanced_accuracy"]
    row = [NAME[m]] + [f"{b[t]:.2f}" for t in TASKS]
    if m in THINK:
        a = think_acc(m)
        row += [f"{a[(t, 'none')]:.2f}" for t in TASKS] + [str(THINK[m]["tokens_mean"])]
    else:
        row += ["n/a"] * 4
    out.append("| " + " | ".join(row) + " |")
out += ["", "Thinking-on accuracy is the mean over margin (income) or status x hours (ABAWD) cells at cue = none; ABAWD errors with",
        "thinking are concentrated in the child-15 trap cell (see docs/results/design_B_rules_pilot.md).", ""]

out += ["## T2. Paired deservingness contrasts, dP(YES) hi - lo, 95% base-clustered bootstrap CI", "",
        "Thinking off: first-token P(YES), same item otherwise. Thinking on: generated verdict (0/1). control = blameless job loss vs fired;",
        "effort = 8 applications/week vs 1 in two months. Both cues are legally irrelevant in every task.", "",
        "| model | task | control hi-lo, off | effort hi-lo, off | control hi-lo, on | effort hi-lo, on |", "| --- | --- | --- | --- | --- | --- |"]
for m in MODELS:
    for t in TASKS:
        c = FT[m]["cue_contrasts_hi_minus_lo_clustered"]
        row = [NAME[m], t, ci(c[f"{t}|control_high-control_low"]["dP_yes"]), ci(c[f"{t}|effort_high-effort_low"]["dP_yes"])]
        if m in THINK:
            k = THINK[m]["contrasts_dPyes_[mean,lo,hi,n]"]
            row += [ci(k[f"{t}|control_high-control_low|all"]), ci(k[f"{t}|effort_high-effort_low|all"])]
        else:
            row += ["n/a", "n/a"]
        out.append("| " + " | ".join(row) + " |")
out += ["", "Groups per contrast (off): gross 248 (31 bases), elig 148 (27 bases), ABAWD 800 (40 bases). On: gross 60, elig 74, ABAWD 150 groups.", ""]

out += ["## T3. Any added sentence moves direct verdicts: cue minus none, income tasks, thinking off (dP(YES), clustered CI)", "",
        "| model | control_high | control_low | effort_high | effort_low | non-moral control (car) |", "| --- | --- | --- | --- | --- | --- |"]
for m in MODELS:
    e = FT[m]["cue_effects_should_not_change"]
    out.append("| " + " | ".join([NAME[m]] + [ci(e[f"income|{c}"]["dP_yes"]) for c in
                                  ("control_high", "control_low", "effort_high", "effort_low", "valence_neg")]) + " |")
out += ["", "The non-moral control is as large as or larger than the deservingness cues, so only the paired hi - lo contrasts (T2) are interpretable.", ""]

out += ["## T4. Reasoning mentions the cue (share of traces, thinking on)", "",
        "| model | task | control_high | control_low | effort_high | effort_low | non-moral |", "| --- | --- | --- | --- | --- | --- | --- |"]
for m in THINK:
    men = THINK[m]["cue_mentioned_in_reasoning"]
    for t in TASKS:
        out.append("| " + " | ".join([NAME[m], t] + [f"{men[f'{t}|{c}']:.2f}" if f"{t}|{c}" in men else "-" for c in
                                      ("control_high", "control_low", "effort_high", "effort_low", "valence_neg")]) + " |")
out += ["", "Mention is a regex over the trace (src/eval/score_rules_think.py CUE_WORDS); it describes, it does not score reliance.", ""]

out += ["## T5. Error direction, thinking off (items)", "", "| model | errors | wrongful denial | wrongful approval | YES rate vs gold (gross / elig / ABAWD) |", "| --- | --- | --- | --- | --- |"]
for m in MODELS:
    e, y = FT[m]["errors"], FT[m]["yes_rate_vs_gold"]
    out.append(f"| {NAME[m]} | {e['n']} | {e['wrongful_denial']} | {e['wrongful_approval']} | " +
               " / ".join(f"{y[t][0]:.2f} vs {y[t][1]:.2f}" for t in TASKS) + " |")
out.append("")
agr = ROOT / "results/rules_think/agreement"
if agr.exists():
    out += ["## T7. Noise floor and protocol ladder: verdict agreement and cue-free flip rate between runs (thinking on)", "",
            "| model | comparison | agreement gross / elig / ABAWD | flip rate at cue = none gross / elig / ABAWD | accuracy of second run gross / elig / ABAWD |",
            "| --- | --- | --- | --- | --- |"]
    for m in MODELS:
        for tag, label in (("s0_vs_s1", "seed 0 vs seed 1"), ("on_vs_off", "thinking on vs off (same prompt)"), ("off_s0_vs_s1", "thinking off, seed 0 vs seed 1"), ("off_vs_free", "step-by-step vs free generation (thinking off)"), ("free_s0_vs_s1", "free generation, seed 0 vs seed 1")):
            f = agr / f"{m}_{tag}.json"
            if f.exists():
                a = json.load(open(f))
                fmt = lambda d, k=None: " / ".join(f"{(d[t][0] if isinstance(d[t], list) else d[t]):.3f}" for t in TASKS)
                out.append(f"| {NAME[m]} | {label} | {fmt(a['agreement_by_task'])} | {fmt(a['flip_rate_at_cue_none_by_task'])} | {fmt(a['accuracy_b_by_task'])} |")
    out.append("")
ns = ROOT / "results/rules_pilot_nosanction"
if ns.exists() and any(ns.glob("score_*.json")):
    out += ["## T9. Sanction check: direct-readout paired contrasts (P(YES), clustered CI) with the original packet vs the packet stating that the reason for a past job loss triggers no sanction", "",
            "| model | task | control hi-lo, original | control hi-lo, no-sanction packet | effort hi-lo, original | effort hi-lo, no-sanction packet |", "| --- | --- | --- | --- | --- | --- |"]
    for m in MODELS:
        f = ns / f"score_{m}.json"
        if not f.exists():
            continue
        b = json.load(open(f))[m]["cue_contrasts_hi_minus_lo_clustered"]; a = FT[m]["cue_contrasts_hi_minus_lo_clustered"]
        for t in TASKS:
            kc, ke = f"{t}|control_high-control_low", f"{t}|effort_high-effort_low"
            out.append(f"| {NAME[m]} | {t} | {ci(a[kc]['dP_yes'])} | {ci(b[kc]['dP_yes'])} | {ci(a[ke]['dP_yes'])} | {ci(b[ke]['dP_yes'])} |")
    out.append("")
cs = ROOT / "results/common_scale/contrasts.md"
if cs.exists():
    out += ["## T8. Both readouts on the verdict scale (thinking subsample, narrative): paired hi-lo verdict differences, clustered CIs, flips, and what a zero excludes", "",
            cs.read_text().rstrip(), "",
            "Zero bound = largest item-level flip rate (rule of three, 3/n) and largest per-base flip probability (1 - 0.05^(1/n_bases)) consistent with the observed zero at 95%. src/eval/score_common_scale.py.", ""]
cq = ROOT / "results/consequence/elig_narrative.md"
if cq.exists():
    out += ["## T6. Consequence on a synthetic near-threshold caseload (elig, narrative; src/eval/consequence.py)", "", cq.read_text().rstrip(), "",
            "Equal base weights primary; HWGT weights secondary. See results/consequence/README.md for the flip concentration.", ""]
(ROOT / "docs/paper1/tables.md").write_text("\n".join(out))
print("\n".join(out))
